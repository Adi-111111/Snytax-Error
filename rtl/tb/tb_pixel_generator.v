    task axi_write;
        input [6:0]  reg_index;
        input [31:0] data;
        begin
            @(posedge clk);
            awaddr  <= (reg_index << 2);
            awvalid <= 1;
            wdata   <= data;
            wvalid  <= 1;
            @(posedge clk);
            while (!(awready && wready)) @(posedge clk);
            awvalid <= 0;
            wvalid  <= 0;
            @(posedge clk);
            while (!bvalid) @(posedge clk);
            @(posedge clk);
        end
    endtask

    task write_weight;
        input [1:0]  layer;
        input [5:0]  neuron;
        input [7:0]  col;
        input [7:0]  val;
        reg   [15:0] addr;
        begin
            addr = {layer, neuron, col};
            axi_write(7'd69, {16'h0, addr});
            axi_write(7'd70, {24'h0, val});
            axi_write(7'd71, 32'd1);
            axi_write(7'd71, 32'd0);
        end
    endtask

    integer stream_count = 0;
    integer cycle_count  = 0;
    integer pixel_count  = 0;
    reg     weights_loaded = 0;

